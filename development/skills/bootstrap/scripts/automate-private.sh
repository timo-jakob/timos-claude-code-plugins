#!/usr/bin/env bash
# automate-private.sh — private-repo bootstrap automation:
#   1. docker compose up -d for SonarQube CE + Postgres
#   2. Wait for SonarQube to be healthy
#   3. Generate random admin password, store in macOS Keychain
#   4. Change admin password via API
#   5. Mint an analysis token
#   6. Create project, create Zero Tolerance Quality Gate, assign it
#   7. Set GitHub secrets (SONAR_TOKEN, SONAR_HOST_URL)
#   8. Register a self-hosted GitHub Actions runner as a launchd service
#   9. Apply branch protection
#
# Usage:
#   automate-private.sh --project-key KEY --project-name NAME \
#                       --default-branch main \
#                       --has-dockerfile true|false

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)"
REPO_ROOT="$(pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

PROJECT_KEY=""
PROJECT_NAME=""
DEFAULT_BRANCH="main"
HAS_DOCKERFILE="false"
SONAR_HOST="http://localhost:9000"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --project-key)    PROJECT_KEY="$2"; shift 2 ;;
    --project-name)   PROJECT_NAME="$2"; shift 2 ;;
    --default-branch) DEFAULT_BRANCH="$2"; shift 2 ;;
    --has-dockerfile) HAS_DOCKERFILE="$2"; shift 2 ;;
    --sonar-host)     SONAR_HOST="$2"; shift 2 ;;   # override for non-localhost
    *) die "Unknown argument: $1" ;;
  esac
done

[[ -n "$PROJECT_KEY"  ]] || die "--project-key required"
[[ -n "$PROJECT_NAME" ]] || die "--project-name required"

# Tools the private-path automation directly invokes. Fail-fast with a
# preflight-pointer instead of a confusing later failure. (`security` and
# `launchctl` ship with macOS and are checked by require_macos elsewhere.)
require_tools curl jq gh docker

KEYCHAIN_SERVICE="sonarqube-local-admin"
COMPOSE_DIR="$REPO_ROOT/infra/sonarqube"
[[ -f "$COMPOSE_DIR/docker-compose.yml" ]] || die "Expected $COMPOSE_DIR/docker-compose.yml — has bootstrap finished generating files?"

# --- 1. Start SonarQube ------------------------------------------------------
echo
info "═══ Starting SonarQube ═══"
( cd "$COMPOSE_DIR" && docker compose up -d )
ok "docker compose up -d issued"

# --- 2. Wait for healthy -----------------------------------------------------
wait_for_sonar_up "$SONAR_HOST" 300

# --- 3. Admin password -------------------------------------------------------
echo
info "═══ Admin password ═══"

# Check Keychain first — if we've already run, reuse the stored password.
ADMIN_PW=""
if security find-generic-password -s "$KEYCHAIN_SERVICE" -a "admin" -w 2>/dev/null; then
  ADMIN_PW=$(security find-generic-password -s "$KEYCHAIN_SERVICE" -a "admin" -w 2>/dev/null)
  ok "Reusing admin password from Keychain (service=$KEYCHAIN_SERVICE)"
else
  ADMIN_PW=$(openssl rand -base64 24 | tr -d '/+=' | head -c 28)
  security add-generic-password -U \
    -s "$KEYCHAIN_SERVICE" \
    -a "admin" \
    -w "$ADMIN_PW" \
    -j "SonarQube CE admin password (generated by /development:bootstrap)"
  ok "Generated admin password and stored in Keychain (service=$KEYCHAIN_SERVICE)"

  # Change from default admin/admin to the generated password.
  info "Changing admin password via API…"
  resp=$(sonar_curl_basic "admin:admin" POST "$SONAR_HOST/api/users/change_password" \
    --data-urlencode "login=admin" \
    --data-urlencode "previousPassword=admin" \
    --data-urlencode "password=$ADMIN_PW")
  _load_http_status
  case "$_http_status" in
    200|204) ok "Admin password changed" ;;
    401)
      warn "Default admin password already changed — your Keychain entry might be stale"
      die "If you know the current password, run: security delete-generic-password -s '$KEYCHAIN_SERVICE' -a admin, then re-run."
      ;;
    *) die "Password change failed (HTTP $_http_status): $resp" ;;
  esac
fi

# --- 4. Create project -------------------------------------------------------
echo
info "═══ Project + Quality Gate ═══"

info "Creating project '$PROJECT_KEY'…"
resp=$(sonar_curl_basic "admin:$ADMIN_PW" POST "$SONAR_HOST/api/projects/create" \
  --data-urlencode "project=$PROJECT_KEY" \
  --data-urlencode "name=$PROJECT_NAME")
_load_http_status
case "$_http_status" in
  200|201) ok "Project created" ;;
  400)
    # Already exists — Sonar returns 400 for duplicate keys. Accept and continue.
    if printf '%s' "$resp" | grep -q "already exists"; then
      ok "Project already exists"
    else
      die "Project create failed (HTTP $_http_status): $resp"
    fi
    ;;
  *) die "Project create failed (HTTP $_http_status): $resp" ;;
esac

# --- 5. Quality Gate ---------------------------------------------------------
# Use admin basic auth via the existing helper, but the create_* helpers expect
# SONAR_TOKEN in env. Mint a token now to drive the gate helpers.
info "Minting analysis token…"
TOKEN_NAME="${PROJECT_KEY}-analysis-$(date +%Y%m%d%H%M%S)"
resp=$(sonar_curl_basic "admin:$ADMIN_PW" POST "$SONAR_HOST/api/user_tokens/generate" \
  --data-urlencode "name=$TOKEN_NAME" \
  --data-urlencode "type=PROJECT_ANALYSIS_TOKEN" \
  --data-urlencode "projectKey=$PROJECT_KEY")
_load_http_status
[[ "$_http_status" =~ ^20 ]] || die "Token generation failed (HTTP $_http_status): $resp"
ANALYSIS_TOKEN=$(printf '%s' "$resp" | jq -r .token)
[[ -n "$ANALYSIS_TOKEN" ]] || die "Empty analysis token in response"
ok "Analysis token minted"

# Now the Quality Gate. Use admin token for gate API; project-analysis token
# doesn't have permission to mutate gates.
ADMIN_TOKEN_NAME="bootstrap-admin-$(date +%Y%m%d%H%M%S)"
resp=$(sonar_curl_basic "admin:$ADMIN_PW" POST "$SONAR_HOST/api/user_tokens/generate" \
  --data-urlencode "name=$ADMIN_TOKEN_NAME")
_load_http_status
[[ "$_http_status" =~ ^20 ]] || die "Admin token generation failed (HTTP $_http_status): $resp"
SONAR_TOKEN=$(printf '%s' "$resp" | jq -r .token)
export SONAR_TOKEN

create_zero_tolerance_gate "$SONAR_HOST" ""
if [[ "${_gate_created:-false}" == "true" ]]; then
  assign_gate_to_project "$SONAR_HOST" "" "$PROJECT_KEY" "Zero Tolerance"
else
  dim "  (Default 'Sonar way' gate is already assigned to new projects — no further action)"
fi

# Revoke the admin token now that the gate is configured — least privilege.
sonar_curl_basic "admin:$ADMIN_PW" POST "$SONAR_HOST/api/user_tokens/revoke" \
  --data-urlencode "name=$ADMIN_TOKEN_NAME" >/dev/null
ok "Revoked bootstrap admin token (analysis token retained)"

# --- 6. GitHub secrets -------------------------------------------------------
echo
info "═══ GitHub secrets ═══"
gh_secret_set_both SONAR_TOKEN    "$ANALYSIS_TOKEN"
gh_secret_set_both SONAR_HOST_URL "$SONAR_HOST"
ok "Secrets set (Actions + Dependabot scopes): SONAR_TOKEN, SONAR_HOST_URL"

# --- 7. Self-hosted runner ---------------------------------------------------
echo
info "═══ Self-hosted GitHub Actions runner ═══"

if ask_yn "Register a self-hosted runner on this machine now?"; then
  REPO=$(gh repo view --json nameWithOwner -q .nameWithOwner)
  RUNNER_DIR="${RUNNER_DIR:-$HOME/actions-runner}"
  if [[ -d "$RUNNER_DIR" && -f "$RUNNER_DIR/svc.sh" ]]; then
    warn "Runner directory already exists at $RUNNER_DIR — skipping download."
  else
    mkdir -p "$RUNNER_DIR"
    ARCH=$(uname -m)
    case "$ARCH" in
      arm64)  RUNNER_OS_ARCH="osx-arm64" ;;
      x86_64) RUNNER_OS_ARCH="osx-x64" ;;
      *)      die "Unsupported architecture: $ARCH" ;;
    esac
    # Fetch the latest runner version from GitHub releases.
    info "Fetching latest runner release info…"
    RUNNER_VERSION=$(gh api repos/actions/runner/releases/latest --jq .tag_name | sed 's/^v//')
    RUNNER_TARBALL="actions-runner-${RUNNER_OS_ARCH}-${RUNNER_VERSION}.tar.gz"
    info "Downloading runner $RUNNER_VERSION ($RUNNER_OS_ARCH)…"
    curl -fsSL -o "$RUNNER_DIR/$RUNNER_TARBALL" \
      "https://github.com/actions/runner/releases/download/v${RUNNER_VERSION}/${RUNNER_TARBALL}"
    ( cd "$RUNNER_DIR" && tar xzf "$RUNNER_TARBALL" && rm "$RUNNER_TARBALL" )
    ok "Runner extracted to $RUNNER_DIR"
  fi

  # Get a registration token (short-lived, single-use).
  info "Requesting registration token…"
  REG_TOKEN=$(gh api -X POST "repos/$REPO/actions/runners/registration-token" --jq .token)
  [[ -n "$REG_TOKEN" ]] || die "Could not retrieve registration token"

  info "Configuring runner…"
  ( cd "$RUNNER_DIR" && ./config.sh \
      --url "https://github.com/$REPO" \
      --token "$REG_TOKEN" \
      --name "$(hostname -s)-sonarqube" \
      --labels "self-hosted,macOS,sonarqube" \
      --unattended \
      --replace )

  info "Installing as a launchd service…"
  ( cd "$RUNNER_DIR" && ./svc.sh install && ./svc.sh start )
  ok "Runner installed and started"
else
  warn "Skipping runner registration — workflows on 'self-hosted' won't run until you do this."
  dim  "See infra/github-runner/README.md for manual steps."
fi

# --- 7b. GitHub Security features (free on private) --------------------------
# Only the Dependabot toggles are free for private repos. Secret scanning,
# push protection, and Private Vulnerability Reporting require GitHub
# Advanced Security ($) on private repos — we skip them here and surface a
# note. Org admins with GHAS can enable manually via repo Settings.
echo
info "═══ GitHub Security features ═══"

GH_REPO_FULL=$(gh repo view --json nameWithOwner -q .nameWithOwner)

info "Enabling Dependabot alerts…"
if gh api --silent -X PUT "repos/$GH_REPO_FULL/vulnerability-alerts" 2>/dev/null; then
  ok "Dependabot alerts enabled"
else
  warn "Dependabot alerts: enable call returned non-zero (likely already enabled)"
fi

info "Enabling Dependabot automated security fixes…"
if gh api --silent -X PUT "repos/$GH_REPO_FULL/automated-security-fixes" 2>/dev/null; then
  ok "Dependabot automated security fixes enabled"
else
  warn "Automated security fixes: enable call returned non-zero (likely already enabled)"
fi

dim "  Secret scanning, push protection, and Private Vulnerability Reporting"
dim "  require GitHub Advanced Security on private repos. If your org has GHAS,"
dim "  enable them manually: repo Settings → Code security and analysis."

# --- 8. Branch protection ----------------------------------------------------
echo
info "═══ Branch protection ═══"
if ask_yn "Apply Zero-Tolerance branch protection on '$DEFAULT_BRANCH' now?"; then
  "$SCRIPT_DIR/branch-protection.sh" \
    --visibility private \
    --has-dockerfile "$HAS_DOCKERFILE" \
    --has-codeql "false" \
    --default-branch "$DEFAULT_BRANCH"
fi

# --- 9. Summary --------------------------------------------------------------
echo
ok "Private-path automation complete"

if [[ "${_gate_created:-false}" == "true" && "${_gate_assigned:-false}" == "true" ]]; then
  gate_summary="Zero Tolerance custom gate (created + assigned)"
elif [[ "${_gate_created:-false}" == "true" ]]; then
  gate_summary="Zero Tolerance gate exists but unassigned; coverage-floor CI step enforces 90%"
else
  gate_summary="Sonar way (custom-gate creation failed; see warning above) — coverage-floor CI step enforces 90%"
fi

cat <<EOF

  SonarQube         $SONAR_HOST  (admin pw in Keychain: service=$KEYCHAIN_SERVICE)
  Project           $PROJECT_KEY
  Sonar gate        $gate_summary
  Coverage 90%      Enforced by the 'coverage-floor' CI step (diff-cover) + pre-push hook,
                    regardless of which Sonar gate is active on the project.
  Secrets set       SONAR_TOKEN, SONAR_HOST_URL  (Actions + Dependabot scopes)
  Runner            $([[ -d "$RUNNER_DIR" ]] && echo "registered + running" || echo "not registered")

  Retrieve admin pw later:
    security find-generic-password -s '$KEYCHAIN_SERVICE' -a admin -w

  Next: push a branch and open a PR — CI will run on the self-hosted runner.
EOF
